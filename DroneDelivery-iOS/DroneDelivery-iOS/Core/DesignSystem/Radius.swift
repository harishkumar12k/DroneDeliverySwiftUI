import SwiftUI

/// Design system tokens for corner radii across UI elements.
public enum Radius {
    /// 4 pt corner radius
    public static let small: CGFloat = 4
    /// 8 pt corner radius
    public static let button: CGFloat = 8
    /// 12 pt corner radius for standard cards
    public static let card: CGFloat = 12
    /// 16 pt corner radius
    public static let large: CGFloat = 16
    /// 24 pt corner radius for pill/capsule shapes
    public static let capsule: CGFloat = 24
}
